// Generates client.js = the layout engine (browser-safe) + the React shell.
// layout.mjs stays the single source of truth; nothing is hand-copied.
import { readFileSync, writeFileSync } from 'node:fs'

const dir = new URL('./', import.meta.url)
let engine = readFileSync(new URL('layout.mjs', dir), 'utf8')

const cut = engine.indexOf('// ---------------- CLI ----------------')
if (cut < 0) throw new Error('CLI marker not found in layout.mjs')
engine = engine.slice(0, cut)
engine = engine.replace(/^import\s[^\n]*\n/gm, '')
engine = engine.replace(/^export\s/gm, '')

const shell = readFileSync(new URL('shell.js', dir), 'utf8')

const out = `/** Generated by build.mjs — do not edit by hand. Source: layout.mjs + shell.js */
window.__ModuleLoader__.load({
  id: '@local/struct-map',
  factory(require) {
${engine}
${shell}
  },
})
`
writeFileSync(new URL('client.js', dir), out, 'utf8')
console.log('client.js written,', out.length, 'bytes')
